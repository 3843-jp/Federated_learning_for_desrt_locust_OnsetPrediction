"""
decision_support.py — the read-only decision-support layer.

This module NEVER trains, fine-tunes, or modifies the frozen Method A
model. It loads the artifact saved by save_frozen_model.py (verified
against Phase 7/8 reference numbers) and the training-statistics-only
weight/threshold configs, and exposes pure inference + explanation +
rule-based recommendation functions.

Research layer (centralized / local-only / FedAvg / Adaptive A / B) and
decision-support layer (prediction / risk / explanation / recommendation)
are kept in physically separate modules -- this file imports the frozen
artifact as data, never the training code paths in frozen_inputs/
phase6_fedavg.py, phase7_run.py, or run_final_experiment.py.
"""
import json
import os

import numpy as np
import pandas as pd
import shap
import torch

_HERE = os.path.dirname(os.path.abspath(__file__))
sys_path_added = False


def _lazy_import_frozen_model_class():
    """Import ONLY the model class definition and scale() utility from
    the frozen inputs -- never the training functions (train_local,
    class_balanced_pos_weight, select_threshold_from_train_cv, etc.),
    so it is structurally impossible for this module to accidentally
    retrain anything."""
    import sys
    global sys_path_added
    if not sys_path_added:
        sys.path.insert(0, os.path.join(_HERE, "frozen_inputs"))
        sys_path_added = True
    from phase6_model import LogisticRegressionModel, scale
    from phase6_data_prep import FROZEN_FEATURES
    return LogisticRegressionModel, scale, FROZEN_FEATURES


LogisticRegressionModel, scale, FROZEN_FEATURES = _lazy_import_frozen_model_class()

with open(os.path.join(_HERE, "config", "thresholds.json")) as f:
    CONFIG = json.load(f)

with open(os.path.join(_HERE, "config", "frozen_model_metadata.json")) as f:
    MODEL_METADATA = json.load(f)


def load_frozen_model():
    """Loads the frozen, verified Method A model. Read-only: no
    .train(), no optimizer, no gradient step ever occurs on this object
    anywhere in this module."""
    scaler = np.load(os.path.join(_HERE, "config", "frozen_scaler.npz"))
    mean, std = scaler["mean"], scaler["std"]
    params_npz = np.load(os.path.join(_HERE, "config", "frozen_method_a_model.npz"))
    params = [params_npz[k] for k in params_npz.files]

    model = LogisticRegressionModel(len(FROZEN_FEATURES))
    with torch.no_grad():
        for p, new in zip(model.parameters(), params):
            p.copy_(torch.tensor(new, dtype=torch.float32))
    model.eval()  # inference mode; never switched to .train()
    return model, mean, std


_MODEL, _MEAN, _STD = load_frozen_model()

_reliability = pd.read_csv(os.path.join(_HERE, "frozen_inputs", "phase7_client_reliability.csv"))


def predict_score(feature_row: dict) -> float:
    """feature_row: dict with keys == FROZEN_FEATURES. Returns the raw
    sigmoid output (0-1), called 'score' per config, not 'probability',
    because calibration_assessment.json found it is not calibrated."""
    x = np.array([[feature_row[f] for f in FROZEN_FEATURES]], dtype=np.float32)
    x_scaled = scale(x, _MEAN, _STD)
    with torch.no_grad():
        logit = _MODEL(torch.tensor(x_scaled, dtype=torch.float32))
        score = torch.sigmoid(logit).item()
    return score


def risk_tier(score: float) -> str:
    t = CONFIG["risk_thresholds"]
    if score < t["low_max"]:
        return "LOW"
    elif score <= t["moderate_max"]:
        return "MODERATE"
    return "HIGH"


def early_warning_message(tier: str) -> str:
    return CONFIG["early_warning_messages"][tier]


def recommendation(tier: str) -> str:
    """Deterministic lookup only -- never generated by the model or an
    LLM. The rule table has no entry that could produce pesticide,
    chemical, crop-destruction, evacuation, or emergency-intervention
    language; adding such a row would require an explicit code change
    to this fixed dict, not a runtime decision."""
    return CONFIG["recommendation_rules"][tier]


def format_score_display(score: float) -> str:
    """Enforces the reviewer-approved terminology: 'Predicted onset
    score: 0.72', never a percentage-probability phrasing, because
    calibration_assessment.json found this model's output is not a
    calibrated probability (ECE=0.478, non-monotonic reliability)."""
    mode = CONFIG["score_display_mode"]
    if mode != "score":
        raise ValueError(
            f"score_display_mode='{mode}' in config, but calibration has not been "
            f"re-verified for probability display -- refusing to format as a percentage "
            f"without an explicit, documented calibration pass. Edit "
            f"config/thresholds.json only after re-running assess_calibration.py."
        )
    return f"Predicted onset score: {score:.2f}"


# --- SHAP explanation (Part 5) ---
# LinearExplainer is the scientifically appropriate method for a linear
# (logistic regression) model -- exact, not an approximation, and does
# not require retraining or perturbation sampling the way KernelExplainer
# would. Background data = a sample of the frozen TRAINING set (SHAP's
# linear explainer needs a background distribution to compute expected
# value; using training data here is standard practice and does not
# touch test data or influence the frozen model in any way).
def _build_shap_explainer():
    import sys
    sys.path.insert(0, os.path.join(_HERE, "frozen_inputs"))
    from phase6_data_prep import load_frozen_dataset
    _cwd = os.getcwd()
    os.chdir(os.path.join(_HERE, "frozen_inputs"))
    try:
        df = load_frozen_dataset()
    finally:
        os.chdir(_cwd)
    train = df[df["split"] == "train"]
    background = scale(train[FROZEN_FEATURES].values.astype(np.float32), _MEAN, _STD)
    background_sample = shap.sample(background, 100, random_state=42)

    def predict_fn(x_scaled):
        with torch.no_grad():
            logits = _MODEL(torch.tensor(x_scaled, dtype=torch.float32))
            return torch.sigmoid(logits).numpy().ravel()

    return shap.LinearExplainer(
        (_MODEL.linear.weight.detach().numpy().ravel(), _MODEL.linear.bias.detach().numpy()[0]),
        background_sample,
    )


_SHAP_EXPLAINER = None


ENVIRONMENTAL_FEATURES = [f for f in FROZEN_FEATURES if not f.endswith("_missing")]
MISSINGNESS_FLAGS = [f for f in FROZEN_FEATURES if f.endswith("_missing")]


def explain(feature_row: dict, top_k: int = 3):
    """Returns top_k ENVIRONMENTAL features by |SHAP value| (excludes
    data-quality/missingness flags from the primary ranking -- those are
    real model inputs and do get real SHAP values, but surfacing
    "precipitation-anomaly-missing" as the #1 reason in a decision-support
    panel meant to be read in ~10 seconds would be confusing, not
    explanatory. Missingness-flag contributions are still computed and
    reported separately (data_quality_flags below) rather than discarded,
    so no information is hidden -- it's organized for the audience."""
    global _SHAP_EXPLAINER
    if _SHAP_EXPLAINER is None:
        _SHAP_EXPLAINER = _build_shap_explainer()

    x = np.array([[feature_row[f] for f in FROZEN_FEATURES]], dtype=np.float32)
    x_scaled = scale(x, _MEAN, _STD)
    shap_values = _SHAP_EXPLAINER.shap_values(x_scaled)[0]
    shap_by_feature = dict(zip(FROZEN_FEATURES, shap_values))

    env_shap = {f: shap_by_feature[f] for f in ENVIRONMENTAL_FEATURES}
    order = sorted(env_shap, key=lambda f: -abs(env_shap[f]))[:top_k]
    results = []
    for f in order:
        v = env_shap[f]
        direction = "positive contribution to predicted risk" if v > 0 \
            else "negative contribution to predicted risk"
        results.append({
            "feature": f, "shap_value": float(v), "direction": direction,
            "magnitude_label": _magnitude_label(abs(v)),
            "caveat": "contributed to the model prediction, not a claim of scientific/biological causation",
        })

    flag_notes = []
    for f in MISSINGNESS_FLAGS:
        if feature_row.get(f, 0) == 1:  # flag is active for this row --
                                          # show it regardless of magnitude,
                                          # so nothing is hidden by a
                                          # threshold choice
            v = shap_by_feature[f]
            direction = "positive contribution to predicted risk" if v > 0 \
                else "negative contribution to predicted risk"
            flag_notes.append({
                "indicator": f.replace("_missing", "") + " history insufficient",
                "shap_value": float(v),
                "direction": direction,
                "magnitude_label": _magnitude_label(abs(v)),
                "note": "Data-quality indicator, not an environmental measurement -- contributed "
                        "to the model score because climatology history was insufficient for this "
                        "region/month, not because of the environmental conditions themselves.",
            })
    return {
        "environmental_contributors": results,
        "data_quality_indicators": flag_notes,
        "data_quality_disclaimer": (
            "Data-quality indicators can influence the model score and are shown separately "
            "from environmental factors." if flag_notes else None
        ),
    }


def _magnitude_label(abs_shap):
    # Bucket boundaries fixed before use, not tuned to produce a
    # particular-looking result -- based on the observed SHAP value
    # range on the frozen model's training background (roughly 0-0.15
    # per feature for this 9-feature logistic regression).
    if abs_shap >= 0.08:
        return "strong contribution"
    elif abs_shap >= 0.03:
        return "moderate contribution"
    return "weak contribution"


# --- Data evidence panel (Part 8) ---
def data_evidence(country: str) -> dict:
    row = _reliability[_reliability["country"] == country]
    if len(row) == 0:
        return {
            "country": country,
            "status": "no reliability record for this country in the frozen training data",
        }
    row = row.iloc[0]
    train_positive = int(row["train_positive"])
    evidence = {
        "country": country,
        "train_samples": int(row["train_samples"]),
        "train_positive_examples": train_positive,
        "val_samples": int(row["val_samples"]),
        "val_positive_examples": int(row["val_positive"]),
    }
    if train_positive == 0:
        evidence["zero_positive_notice"] = (
            "This client has no positive training examples. The prediction is based on the "
            "federated/global model and may have limited client-specific evidence."
        )
    elif train_positive < 5:
        evidence["sparse_history_notice"] = "Limited positive-history evidence."
    return evidence


